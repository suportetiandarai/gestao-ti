create or replace function public.acquire_google_sheet_sync(
  p_source text,
  p_execution_id uuid,
  p_lock_seconds integer default 110
) returns boolean
language plpgsql security definer
set search_path=public,pg_temp as $$
declare acquired boolean;
begin
  update public.google_sheet_sync_state
     set status='running',
         last_attempt_at=now(),
         locked_at=now(),
         lock_expires_at=now()+make_interval(secs=>greatest(30,p_lock_seconds)),
         execution_id=p_execution_id,
         updated_at=now()
   where source=p_source
     and (lock_expires_at is null or lock_expires_at < now() or execution_id=p_execution_id)
  returning true into acquired;
  return coalesce(acquired,false);
end; $$;

create or replace function public.finish_google_sheet_sync(
  p_source text,
  p_execution_id uuid,
  p_success boolean,
  p_records_processed integer,
  p_duration_ms integer,
  p_error_message text default null
) returns boolean
language plpgsql security definer
set search_path=public,pg_temp as $$
declare changed boolean;
begin
  update public.google_sheet_sync_state
     set status=case when p_success then 'success' else 'error' end,
         last_success_at=case when p_success then now() else last_success_at end,
         last_error_at=case when p_success then null else now() end,
         last_error_message=case when p_success then null else left(p_error_message,300) end,
         records_processed=greatest(0,p_records_processed),
         duration_ms=greatest(0,p_duration_ms),
         locked_at=null,
         lock_expires_at=null,
         execution_id=null,
         updated_at=now()
   where source=p_source and execution_id=p_execution_id
  returning true into changed;
  return coalesce(changed,false);
end; $$;

create or replace function public.prune_google_sheet_requests(
  p_source text,
  p_sync_marker uuid,
  p_cutoff_at timestamptz
) returns integer
language plpgsql security definer
set search_path=public,pg_temp as $$
declare affected integer;
begin
  delete from public.google_sheet_requests
   where source=p_source
     and requested_at >= p_cutoff_at
     and sync_marker <> p_sync_marker;
  get diagnostics affected = row_count;
  return affected;
end; $$;

