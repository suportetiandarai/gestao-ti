create table if not exists public.google_sheet_requests (
  id bigint generated by default as identity primary key,
  source text not null check (source in ('timed','training')),
  source_row integer not null check (source_row > 1),
  requested_at timestamptz not null,
  requester_name text not null,
  sector text,
  job_title text,
  training_topic text,
  source_status text,
  dashboard_status text not null check (
    dashboard_status in ('completed','pending','not_completed','scheduled','not_scheduled')
  ),
  sort_priority smallint not null default 3,
  row_hash text not null,
  sync_marker uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (source, source_row)
);

create table if not exists public.google_sheet_sync_state (
  source text primary key check (source in ('timed','training')),
  status text not null default 'idle' check (status in ('idle','running','success','error')),
  last_attempt_at timestamptz,
  last_success_at timestamptz,
  last_error_at timestamptz,
  last_error_message text,
  locked_at timestamptz,
  lock_expires_at timestamptz,
  execution_id uuid,
  records_processed integer not null default 0,
  duration_ms integer,
  updated_at timestamptz not null default now()
);

create table if not exists public.google_sheet_sync_logs (
  id bigint generated by default as identity primary key,
  source text not null check (source in ('timed','training')),
  execution_id uuid not null,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null check (status in ('running','success','error','skipped')),
  records_processed integer not null default 0,
  error_message text,
  duration_ms integer,
  created_at timestamptz not null default now(),
  unique (source, execution_id)
);

create table if not exists public.google_sheet_dashboard_snapshots (
  source text primary key check (source in ('timed','training')),
  total_count integer not null default 0,
  completed_count integer not null default 0,
  pending_count integer not null default 0,
  not_started_count integer not null default 0,
  snapshot_hash text not null,
  snapshot_version bigint not null default 1,
  integration_status text not null default 'not_ready'
    check (integration_status in ('online','delayed','offline','not_ready')),
  cutoff_at timestamptz not null,
  last_synced_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.google_sheet_sync_state(source)
values ('timed'),('training')
on conflict (source) do nothing;

create index if not exists google_sheet_requests_source_status_idx
  on public.google_sheet_requests(source, sort_priority, requested_at desc);
create index if not exists google_sheet_requests_source_requested_idx
  on public.google_sheet_requests(source, requested_at desc);
create index if not exists google_sheet_sync_logs_started_idx
  on public.google_sheet_sync_logs(started_at desc);

